import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { MODULES, esm, cjs, fixedNow } from './helpers.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const exportNames = [
  'CODE', 'LogCageError', 'sanitizeLogLine', 'redactSecrets',
  'sanitizeLogRecord', 'formatSafeJsonLog', 'createLogCage'
];

test('generated CommonJS build is up to date', () => {
  const output = execFileSync(process.execPath, [path.join(root, 'scripts', 'build-cjs.mjs'), '--check'], {
    cwd: root,
    encoding: 'utf8'
  });
  assert.match(output, /up to date/);
});

for (const [label, module] of MODULES) {
  test(label + ' exposes every public export', () => {
    for (const name of exportNames) {
      assert.equal(typeof module[name] !== 'undefined', true, name);
    }
  });

  test(label + ' sanitizeLogLine parity smoke test', () => {
    assert.equal(module.sanitizeLogLine('a\nb\x1b[31m'), 'a\\nb');
  });

  test(label + ' redactSecrets parity smoke test', () => {
    assert.equal(module.redactSecrets('token=abcdef'), 'token=[REDACTED]');
  });

  test(label + ' sanitizeLogRecord parity smoke test', () => {
    assert.deepEqual(JSON.parse(JSON.stringify(module.sanitizeLogRecord({ password: 'x', a: 'b\n' }))), { password: '[REDACTED]', a: 'b\\n' });
  });

  test(label + ' formatSafeJsonLog parity smoke test', () => {
    assert.equal(
      module.formatSafeJsonLog('info', 'x', { a: 1 }, { timestamp: fixedNow() }),
      '{"ts":"' + fixedNow() + '","level":"info","msg":"x","meta":{"a":1}}'
    );
  });

  test(label + ' createLogCage parity smoke test', () => {
    const guard = module.createLogCage({ maxLength: 16 });
    assert.equal(guard.line('x'.repeat(17)), 'xxxxx[truncated]');
  });
}

test('ESM and CJS error objects have parity', () => {
  for (const fn of [() => esm.sanitizeLogLine(1), () => cjs.sanitizeLogLine(1)]) {
    let error;
    try { fn(); } catch (caught) { error = caught; }
    assert.equal(error.name, 'LogCageError');
    assert.equal(error.code, 'ERR_LOGCAGE_INVALID_INPUT');
    assert.equal(typeof error.toJSON(), 'object');
  }
});

test('ESM and CJS produce identical structured output for mixed data', () => {
  const make = () => ({
    password: 'x',
    date: new Date('2026-01-01T00:00:00Z'),
    map: new Map([['a', 1]]),
    set: new Set([1]),
    bytes: new Uint8Array([1, 2]),
    bigint: 1n
  });
  assert.equal(JSON.stringify(esm.sanitizeLogRecord(make())), JSON.stringify(cjs.sanitizeLogRecord(make())));
});

test('package self-reference resolves through ESM exports', async () => {
  const module = await import('logcage');
  assert.equal(typeof module.sanitizeLogLine, 'function');
  assert.equal(module.sanitizeLogLine('a\n'), esm.sanitizeLogLine('a\n'));
});

test('package self-reference resolves through CJS exports', () => {
  assert.equal(typeof cjs.sanitizeLogLine, 'function');
  assert.equal(cjs.sanitizeLogLine('a\n'), esm.sanitizeLogLine('a\n'));
});

test('ESM default export contains the public API', async () => {
  const module = await import('../src/index.mjs');
  for (const name of exportNames) assert.equal(typeof module.default[name] !== 'undefined', true, name);
});

test('CJS default reference is the exported API object', () => {
  assert.equal(cjs.default, cjs);
});

test('generated CJS file has the deterministic build header', () => {
  const output = fs.readFileSync(path.join(root, 'cjs', 'index.cjs'), 'utf8');
  assert.match(output, /Generated by scripts\/build-cjs\.mjs/);
  assert.match(output, /module\.exports\.default = module\.exports/);
});

test('generated CJS does not contain ESM export declarations', () => {
  const output = fs.readFileSync(path.join(root, 'cjs', 'index.cjs'), 'utf8');
  assert.equal(/^export\s/m.test(output), false);
});

test('source of truth contains no CommonJS require call', () => {
  const source = fs.readFileSync(path.join(root, 'src', 'index.mjs'), 'utf8');
  assert.equal(source.includes('require('), false);
});

test('source of truth contains no runtime dependency imports', () => {
  const source = fs.readFileSync(path.join(root, 'src', 'index.mjs'), 'utf8');
  assert.equal(/^import\s/m.test(source), false);
});

