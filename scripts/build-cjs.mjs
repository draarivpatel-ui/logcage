/*
 * Generate the CommonJS build from the single ESM source of truth.
 * The transform is intentionally small, deterministic and auditable.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = await readFile(path.join(root, 'src', 'index.mjs'), 'utf8');
const checkMode = process.argv.includes('--check');

const EXPORT_NAMES = [
  'CODE', 'LogCageError', 'sanitizeLogLine', 'redactSecrets',
  'sanitizeLogRecord', 'formatSafeJsonLog', 'createLogCage'
];

let body = source;
body = body.replace(/^export const /gm, 'const ');
body = body.replace(/^export class /gm, 'class ');
body = body.replace(/^export function /gm, 'function ');
if (!body.includes('export default logcage;')) throw new Error('CJS transform could not find the default export');
body = body.replace('export default logcage;', '');
if (/^export\s/m.test(body)) throw new Error('CJS transform left an export declaration behind');

const output = [
  "'use strict';",
  '',
  '/* Generated by scripts/build-cjs.mjs from src/index.mjs. Do not edit directly. */',
  '',
  body.trim(),
  '',
  'module.exports = {',
  ...EXPORT_NAMES.map((name) => '  ' + name + ','),
  '};',
  '',
  'module.exports.default = module.exports;',
  ''
].join('\n');

const target = path.join(root, 'cjs', 'index.cjs');
if (checkMode) {
  let existing = '';
  try {
    existing = await readFile(target, 'utf8');
  } catch {
    existing = '';
  }
  if (existing !== output) {
    throw new Error('cjs/index.cjs is not up to date; run node scripts/build-cjs.mjs');
  }
  process.stdout.write('cjs/index.cjs is up to date\n');
} else {
  await mkdir(path.join(root, 'cjs'), { recursive: true });
  await writeFile(target, output, 'utf8');
  process.stdout.write('cjs/index.cjs generated from src/index.mjs\n');
}
